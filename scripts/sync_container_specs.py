#!/usr/bin/env python3
"""Generate the container specs and process->image map from modules/local/*.nf.

    scripts/sync_container_specs.py            # write envs/process/*.yml + conf/containers.config
    scripts/sync_container_specs.py --check    # exit 3 if either is out of date

WHY GENERATED AND NOT WRITTEN
-----------------------------
`-profile docker` and `-profile singularity` existed in nextflow.config for months and
declared NO container image anywhere - advertised and absent, which is this project's
recurring shape. The obvious fix is to hand-write a container line per process. The
obvious fix also rots: a pin moves in a module, nobody edits the container map, and the
two routes silently run different versions of the same tool. The conda route would be
correct and the container route would be wrong, and the only visible difference would be
in results.

So the modules are the single source of truth. Each distinct conda spec becomes one small
environment file and one image; this script writes both, and `--check` fails the suite
when they disagree with the modules.

WHY NOT ONE IMAGE WITH EVERYTHING IN IT
---------------------------------------
Because it was measured. Installing kraken2 beside mmseqs2/hmmer/mafft makes the solver
resolve kraken2 2.0.8-beta (2019), which has no `--report-minimizer-data` - the flag the
whole stage-1 design rests on. An index built with it works and carries none of the
evidence the pipeline scores on (D49). A fat image reproduces that trap exactly, so the
images stay per-spec, which is also why they are small and build in parallel.

WHY NOT BIOCONTAINERS
---------------------
Single-tool biocontainers would do for 8 of the 13 specs, but 5 processes need two or
three tools together (minimap2+samtools, samtools+python, mmseqs2+seqkit, hmmer+seqkit),
and those need a "mulled" image whose name is a hash of the package set - one that exists
only if somebody has already built that exact combination. Building our own from the same
pins the conda route uses is both fewer moving parts and a stronger guarantee: the two
routes cannot drift because they read the same line.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
MODULES = REPO / "modules" / "local"
SPEC_DIR = REPO / "envs" / "process"
CONFIG = REPO / "conf" / "containers.config"

EXIT_OK, EXIT_STALE = 0, 3

# Processes with no conda directive, and why. PAVIAN_REPORT is the only one: Pavian and
# two of its dependencies install from GitHub, so no conda spec can declare them, and the
# process is off by default (`pavian_html = false`) and documented as running in the host
# environment. Giving it an image that does not contain Pavian would be worse than giving
# it none - it would fail inside a container instead of failing where the operator can see
# why.
NO_CONTAINER = {"PAVIAN_REPORT": "Pavian installs from GitHub; off by default, host-only"}

# `#` IS NOT A COMMENT IN A NEXTFLOW CONFIG. The first generated version of
# conf/containers.config led with one and would have been a parse error on every run under
# a container profile - caught by compiling it, not by reading it.
HEADER_YAML = "# GENERATED by scripts/sync_container_specs.py - do not edit.\n"
HEADER_NF = "// GENERATED by scripts/sync_container_specs.py - do not edit.\n"


def manifest_version() -> str:
    """The pipeline version, read from nextflow.config's manifest.

    Written into the image tags LITERALLY rather than referenced as a param. `params` are
    not available to each other at parse time in a way that survives every profile
    combination, and a tag that resolves to an empty string pulls `image:` - which Docker
    reads as `:latest`, the one tag that must never be used here: it would silently run
    whatever was built most recently against a pipeline pinned to something else.
    """
    cfg = (REPO / "nextflow.config").read_text(encoding="utf-8")
    m = re.search(r"version\s*=\s*'([^']+)'", cfg)
    if not m:
        raise SystemExit("ERROR: no manifest version in nextflow.config")
    return m.group(1)


def parse_modules() -> dict[str, str]:
    """process name -> conda spec string, in file order."""
    out: dict[str, str] = {}
    for f in sorted(MODULES.glob("*.nf")):
        text = f.read_text(encoding="utf-8")
        for m in re.finditer(r"process\s+(\w+)\s*\{(.*?)(?=\nprocess\s|\Z)", text, re.S):
            name, body = m.group(1), m.group(2)
            spec = re.search(r"conda\s+['\"]([^'\"]+)['\"]", body)
            out[name] = spec.group(1).strip() if spec else ""
    return out


def slug(spec: str) -> str:
    """A stable, readable image name for a spec.

    Keyed on the TOOLS, not their versions: the version belongs in the image tag, which
    is the pipeline version, so a pin change rebuilds the same image name. Sorted, so
    reordering two packages in a module does not rename an image.
    """
    names = sorted(p.split("::")[-1].split("=")[0] for p in spec.split())
    return "-".join(names)


def spec_yaml(spec: str) -> str:
    """A conda environment file for one process's spec.

    Channels are declared in the same order as envs/*.yml and NOTHING else is added:
    `defaults` imposes licence conditions on a reader who did not choose it, and this
    project's own environments inherited plotly and r channels from a global config once.
    """
    deps = []
    for part in spec.split():
        if "::" in part:
            chan, pkg = part.split("::", 1)
            deps.append((chan, pkg))
        else:
            deps.append(("", part))
    lines = [HEADER_YAML,
             "# Pins copied from the `conda` directive of the process(es) that use them,\n",
             "# so the container and conda routes cannot run different versions.\n",
             f"name: btf-{slug(spec)}\n",
             "channels:\n  - conda-forge\n  - bioconda\n",
             "dependencies:\n"]
    for chan, pkg in deps:
        lines.append(f"  - {chan + '::' if chan else ''}{pkg}\n")
    return "".join(lines)


def render_config(by_process: dict[str, str]) -> str:
    """conf/containers.config: one `withName` per process, plus the version tag."""
    specs = sorted({s for s in by_process.values() if s})
    version = manifest_version()
    lines = [
        HEADER_NF,
        "//\n",
        "// Loaded by the docker, podman, singularity and apptainer profiles. Each image\n",
        "// is built from envs/process/<name>.yml, which carries the SAME pins as the\n",
        "// process's conda directive - see scripts/sync_container_specs.py for why this\n",
        "// file is generated rather than maintained.\n",
        "//\n",
        "// The tag is the pipeline version from the manifest, written in literally, so an\n",
        "// image can never be newer or older than the pipeline that asks for it and no\n",
        "// profile combination can resolve it to `latest`.\n",
        "//\n",
        "// container_prefix is a PREFIX and not a registry, so it can be overridden to\n",
        "// nothing useful-looking: `--container_prefix biothreatfinder-` runs images built\n",
        "// locally with containers/Dockerfile, and a registry path runs them from a\n",
        "// mirror. A registry variable with a `/` joined on cannot express the local case.\n",
        "\n",
        "params {\n",
        "    container_prefix = 'ghcr.io/duceppemo/biothreatfinder-'\n",
        "}\n",
        "\n",
        "process {\n",
    ]
    for name in by_process:
        spec = by_process[name]
        if not spec:
            why = NO_CONTAINER.get(name, "no conda directive")
            lines.append(f"    // {name}: no container - {why}\n")
            continue
        img = f"${{params.container_prefix}}{slug(spec)}"
        lines.append(f"    withName: '{name}' {{\n")
        lines.append(f'        container = "{img}:{version}"\n')
        lines.append("    }\n")
    lines.append("}\n")
    lines.append("\n")
    lines.append(f"// {len(specs)} distinct image(s): "
                 + ", ".join(slug(s) for s in specs) + "\n")
    return "".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="write nothing; exit 3 if the generated files are out of date")
    args = ap.parse_args(argv)

    by_process = parse_modules()
    if not by_process:
        print("UNDETERMINED: no processes found under modules/local/", file=sys.stderr)
        return 1

    wanted = {SPEC_DIR / f"{slug(s)}.yml": spec_yaml(s)
              for s in {v for v in by_process.values() if v}}
    wanted[CONFIG] = render_config(by_process)

    stale = []
    for path, body in sorted(wanted.items()):
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != body:
            stale.append(path.relative_to(REPO))

    # A spec file for a process that no longer exists is just as wrong as a missing one:
    # it would keep an image in the build matrix that nothing runs.
    orphans = []
    if SPEC_DIR.is_dir():
        orphans = [p.relative_to(REPO) for p in sorted(SPEC_DIR.glob("*.yml"))
                   if p not in wanted]

    if args.check:
        if not stale and not orphans:
            print(f"FRESH: {len(wanted) - 1} image spec(s) and the process map match "
                  f"{len(by_process)} process(es) in modules/local/")
            return EXIT_OK
        print("STALE: the container specs do not match modules/local/")
        for p in stale:
            print(f"  out of date: {p}")
        for p in orphans:
            print(f"  orphaned (no process uses this spec): {p}")
        print("Regenerate: scripts/sync_container_specs.py")
        return EXIT_STALE

    SPEC_DIR.mkdir(parents=True, exist_ok=True)
    for path, body in sorted(wanted.items()):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body, encoding="utf-8")
        print(f"wrote {path.relative_to(REPO)}")
    for p in orphans:
        (REPO / p).unlink()
        print(f"removed orphan {p}")
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
